const productImage = (name: string, category: string, index: number): string => {
  const productType = productTypePrompt[category] || 'agricultural product'
  const prompt = `photorealistic e-commerce product photo of the exact product ${name}; product type ${productType}; category ${category}; show only the named product, isolated on a clean white background, no people, no text, no watermark, no unrelated farming equipment`
  return `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=900&height=600&seed=agrirent-${index + 1}&nologo=true`
}

const catalogEntries: CatalogItem[] = [...existingCatalog, ...extraCatalog].map((item, index) => {
  const image = productImage(item.name, item.cat, index)
  return {
    ...item,
    img: image,
    gallery: [image],
  }
})

if (new Set(catalogEntries.map((item) => item.img)).size !== catalogEntries.length) {
  throw new Error('Catalog image mapping contains duplicate product image URLs')
}

export const catalog: CatalogItem[] = catalogEntries

export const isSupply = (cat: string) => cat === 'Seeds'

export function findCatalogItem(id: string): CatalogItem | undefined {
  return catalog.find((item) => item.id === id)
}
